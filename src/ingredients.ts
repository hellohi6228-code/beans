/** "Gochujang 고추장" — English, then the reader's language when there is one. */
export function ingredientName(i: Ingredient, lang: Lang): string {
  const other = lang === 'en' ? undefined : i[lang];
  return other && other.toLowerCase() !== i.en.toLowerCase() ? `${i.en} ${other}` : i.en;
}

/** Every name an ingredient goes by, for search. */
export const namesOf = (i: Ingredient) =>
  [i.en, i.zh, i.ko, i.ja, i.vi, i.th, i.es, i.it, ...(i.also ?? [])].filter((s): s is string => !!s);

export const findIngredient = (cuisine: Cuisine, en: string) => INGREDIENTS[cuisine].find((i) => i.en === en);
